export const ENNEA_REQUIRED_FIELDS = ["motive","fear","coping","strength","cost","stress","observe"] as const;

export function enneaProfileComplete(id: string): boolean {
  const p = ENNEA_PROFILES[id];
  if (!p) return false;
  if (p.confusions.length < 3 || p.wings.length < 2) return false;
  const total = ENNEA_REQUIRED_FIELDS.reduce((s, k) => s + (p[k] || "").length, 0)
    + p.confusions.reduce((s, c) => s + c.contrast.length, 0)
    + p.wings.reduce((s, w) => s + w.text.length, 0);
  return ENNEA_REQUIRED_FIELDS.every((k) => (p[k] || "").length >= 40) && total >= 700;
}

function enneaSections(p: EnneaProfile, wingFocus: string = ""): ReadingSection[] {
  const conf = p.confusions.map((c) => `${c.other.slice(1)} 号：${c.contrast}`).join("\n\n");
  const wings = p.wings.map((w) => {
    const mark = wingFocus && w.id === wingFocus ? "（本次测量更贴近这一翼，仍属理论对照。）\n" : "";
    return `${w.label}：${mark}${w.text}`;
  }).join("\n\n");
  const wingLead = wingFocus
    ? "翼型已在测量上锁出，下面仍把两翼都写出，便于对照；不要把未选中的那一翼删掉当成不存在。"
    : "翼型尚未锁定或主型未定，下面两翼都只供对照，不作为已确认结果。";
  return [
    { title: "核心动机", body: p.motive },
    { title: "核心恐惧", body: p.fear },
    { title: "常用应对", body: p.coping },
    { title: "优势", body: p.strength },
    { title: "代价", body: p.cost },
    { title: "压力下的常见表现（模型描述，非必然、非诊断）", body: p.stress },
    { title: "易混型的具体差别", body: conf },
    { title: "翼型差异", body: wingLead + "\n\n" + wings },
    { title: "自我观察建议", body: p.observe },
  ];
}

export function enneaBlock(id: string, locked: boolean, wingFocus: string = ""): ReadingBlock {
  const p = ENNEA_PROFILES[id];
  return {
    id,
    title: `${p.name} · ${p.epithet}`,
    badge: locked ? "已锁定主型 · 以下是理论档案，不是对你的诊断" : "暂定候选人 · 尚未锁定，请对照，不要当成已确认",
    locked,
    sections: enneaSections(p, wingFocus),
  };
}

